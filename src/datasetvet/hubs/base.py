"""Hub adapter and source resolver interfaces (PLAN.md section 6).

Phase 2 (task 2.3) fills in the data classes and the registry. The method set below is the
contract every hub (Hugging Face in v1; Kaggle, Zenodo, GitHub-hosted in v2) implements.
"""

from __future__ import annotations

from collections.abc import Iterator
from typing import Any, Protocol

# Placeholders until task 2.1 defines them in model.py.
DatasetRef = Card = RepoFile = TextBlob = LicenceClaim = LinkRef = ParentRef = Any
SplitSource = ScanPlan = LinkResult = RecordBatch = Any


class HubAdapter(Protocol):
    name: str

    def matches(self, ref: str) -> bool: ...
    def resolve(self, ref: str) -> DatasetRef: ...
    def card(self, ds: DatasetRef) -> Card: ...
    def files(self, ds: DatasetRef) -> list[RepoFile]: ...
    def read_text(self, ds: DatasetRef, path: str, max_bytes: int) -> TextBlob: ...
    def native_licences(self, ds: DatasetRef) -> list[LicenceClaim]: ...
    def stated_sources(self, card: Card) -> list[LinkRef]: ...
    def parents(self, card: Card) -> list[ParentRef]: ...
    def splits(self, ds: DatasetRef) -> list[SplitSource]: ...
    def open_split(self, split: SplitSource, plan: ScanPlan) -> Iterator[RecordBatch]: ...


class SourceResolver(Protocol):
    def matches(self, url: str) -> bool: ...
    def licence_claims(self, url: str) -> list[LicenceClaim]: ...
    def link_status(self, url: str) -> LinkResult: ...
